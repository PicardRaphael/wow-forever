"""SkillUp Forever lu pour les métiers (plan « Sources d'abord », étape b ; décisions 272 et 288) : seuils de chaque
recette (orange, jaune, vert, gris) générés par l'addon depuis le client d'un build nommé dans l'en-tête, métier de la
recette, noms. `forever_lookup(kind="profession")` rend, au rang actuel, les recettes qui font encore monter le métier
(orange d'abord : gain sûr ; puis jaune), la fraîcheur de la source (build de ses données contre la version installée)
et rappelle que SkillUp calcule en jeu l'itinéraire jusqu'au rang visé (`/skillup`) : on lit, on ne recalcule pas.

Addon fabriqué dans `tmp_path` (structure de SkillUp Forever) ; recettes, seuils et noms inventés."""

from conftest import LOCAL_VERSION
from forever.pipeline.skillup import read_skillup

HEADER = f"-- Generated by tools/gen_thresholds.py - do not edit.\n-- Source: wago.tools DB2, wow_classic_beta {LOCAL_VERSION}, 2026-10-17.\n"


def write_skillup(root, build=LOCAL_VERSION):
    data = root / "Interface" / "AddOns" / "SkillUpForever" / "Data"
    data.mkdir(parents=True)
    head = HEADER.replace(LOCAL_VERSION, build)
    (data / "Thresholds.lua").write_text(
        head + "local _, ns = ...\nns.Thresholds = {\n"
        "\t[900001] = { 1, 30, 45, 60 }, -- Recette Un\n"
        "\t[900002] = { 20, 50, 65, 80 }, -- Recette Deux\n"
        "\t[900003] = { 70, 90, 105, 120 }, -- Recette Trois\n"
        "\t[900004] = { 1, 10, 15, 20 }, -- Recette Grise\n"
        "}\n",
        encoding="utf-8",
    )
    (data / "Recipes.lua").write_text(
        "local _, ns = ...\nns.RecipeData = {\n"
        "\t[900001] = { skillLine = 900, reagents = {}, output = false },\n"
        "\t[900002] = { skillLine = 900, reagents = {}, output = false },\n"
        "\t[900003] = { skillLine = 900, reagents = {}, output = false },\n"
        "\t[900004] = { skillLine = 900, reagents = {}, output = false },\n"
        '}\nns.ProfessionSkillLines = {\n\t["Métier Test"] = 900,\n}\n',
        encoding="utf-8",
    )
    return root


def test_thresholds_and_professions_are_read(tmp_path):
    root = write_skillup(tmp_path)
    s = read_skillup(root / "Interface" / "AddOns")
    assert s["build"] == LOCAL_VERSION and s["date"] == "2026-10-17"
    assert s["professions"] == {"Métier Test": 900}
    assert s["recipes"][900002] == {"skill_line": 900, "name": "Recette Deux", "thresholds": (20, 50, 65, 80)}


def test_profession_guide_lists_what_still_raises_the_skill(tmp_path, make_deps):
    from forever.lookup import lookup_profession

    deps = make_deps(wow_dir=write_skillup(tmp_path))
    out = lookup_profession(deps, "Métier Test", rank=35)
    names = [r["name"] for r in out["recipes"]]
    assert names == [
        "Recette Deux",
        "Recette Un",
    ]  # orange (gain sûr) d'abord, puis jaune ; grise et trop haute exclues
    assert out["recipes"][0]["color"] == "orange" and out["recipes"][1]["color"] == "jaune"
    assert out["freshness"]["status"] == "à jour" and "/skillup" in out["in_game"]
    assert out["provenance"]["certainty"] == "suppose"


def test_profession_guide_says_when_the_source_is_older(tmp_path, make_deps):
    from forever.lookup import lookup_profession

    deps = make_deps(wow_dir=write_skillup(tmp_path, build="1.60.1.70001"))
    out = lookup_profession(deps, "Métier Test", rank=25)
    assert out["freshness"]["status"] == "en retard"
    assert any("calcul en cours de mise à jour" in a or "antérieure" in a for a in out["provenance"]["assumptions"])


def test_profession_guide_without_skillup(make_deps, tmp_path):
    from forever.lookup import lookup_profession

    out = lookup_profession(make_deps(wow_dir=tmp_path / "vide"), "Alchemy", rank=1)
    assert out["available"] is False and out["recipes"] == []
