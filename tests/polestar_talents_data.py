"""Addon Polestar synthétique pour les tests (LV1) : `Polestar/Talents/Builds.lua` écrit dans un dossier temporaire.

Rien du fichier réel n'est copié : on reprend seulement sa **forme** (relevée dans Polestar 0.3.1, fichier généré par
`forge data talents build`) : `T.Register({ class, summary = L["…"], specs, nodes = { [nœud] = { entrée, rangs, sort,
colonne, rangée, colonne, "Nom" } }, builds = { { key, spec, split, picks = { { nœud, rang }… }, notes = { [niveau] =
L["…"] } } } })`. Les talents, nœuds et sorts viennent de notre `classes.json` de fixture."""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

FOLDER = "Polestar"
TOC_VERSION = "0.0.1-fixture"
WRITTEN_ON = "1.60.1.70000"


def talents_of(classes_json: Path, class_name: str) -> dict[str, dict[str, Any]]:
    """Talents d'une classe de fixture par clé (nom, nœud, sort, arbre)."""
    doc = json.loads(classes_json.read_text(encoding="utf-8"))
    cls = doc["classes"][class_name]
    return {t["key"]: t for tree in cls["trees"] for t in tree["talents"]}


def _s(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def write_polestar(
    wow_dir: Path,
    classes_json: Path,
    class_name: str,
    builds: Sequence[Mapping[str, Any]],
    *,
    extra_nodes: Mapping[int, str] | None = None,
    renamed_nodes: Mapping[int, str] | None = None,
) -> Path:
    """Écrit `<wow_dir>/Interface/AddOns/Polestar/` (`.toc` et `Talents/Builds.lua`) pour une classe.

    `builds` : `{"key", "spec", "split", "picks": [clé ou ("nœud", n)…], "notes": {niveau: texte}}` ; une clé est
    remplacée par le nœud et le nom de nos données, un `("nœud", n)` est un nœud de `extra_nodes` (nom absent du
    client). `renamed_nodes` : nœud de nos données porté sous un autre nom (nœud réaffecté depuis l'écriture)."""
    talents = talents_of(classes_json, class_name)
    file_name = json.loads(classes_json.read_text(encoding="utf-8"))["classes"][class_name]["file"]
    nodes: dict[int, tuple[int, int, str]] = {}  # nœud -> (rangs, sort, nom)
    for t in talents.values():
        nodes[int(t["node_id"])] = (int(t["max"]), int(t["spell_id"] or 0), str(t["name"]))
    for node, name in (renamed_nodes or {}).items():
        rangs, spell, _ = nodes[node]
        nodes[node] = (rangs, spell + 1, name)
    for node, name in (extra_nodes or {}).items():
        nodes[node] = (1, 0, name)
    lines = [
        (
            "-- Generated by `forge data talents build` from talents/forever/*.json and the Forever "
            f"{WRITTEN_ON} trait tables (wago.tools). Do not edit: rebuild with that command."
        ),
        "",
        "local ADDON, ns = ...",
        "local T = ns.Talents",
        "local L = ns.L",
        "",
        "T.Register({",
        f'\tclass = "{file_name}", tree = 1, prereq = "full",',
        f'\tsource = L[{_s("Polestar (fixture)")}], url = "https://example.invalid/talents",',
        f"\tsummary = L[{_s('Résumé de fixture.')}],",
        '\tspecs = { "A", "B", "C" },',
        "\tnodes = {",
    ]
    for node, (rangs, spell, name) in sorted(nodes.items()):
        lines.append(f"\t\t[{node}] = {{ {node + 1}, {rangs}, {spell}, 1, 1, 1, {_s(name)} }},")
    lines += ["\t},", "\tbuilds = {"]
    for b in builds:
        picks = []
        taken: dict[Any, int] = {}
        for p in b["picks"]:
            node = p[1] if isinstance(p, tuple) else int(talents[p]["node_id"])
            taken[node] = taken.get(node, 0) + 1
            picks.append(f"{{ {node}, {taken[node]} }}")
        lines += [
            "\t\t{",
            (
                f'\t\t\tkey = "{b["key"]}", spec = {b.get("spec", 1)}, split = "{b.get("split", "0/0/0")}", '
                'link = "https://example.invalid",'
            ),
            "\t\t\t-- in order, one point each: { node, rank }",
            "\t\t\tpicks = {",
            "\t\t\t\t" + ", ".join(picks) + ",",
            "\t\t\t},",
            "\t\t\tnotes = {",
        ]
        for level, text in sorted((b.get("notes") or {}).items()):
            lines.append(f"\t\t\t\t[{level}] = L[{_s(text)}],")
        lines += ["\t\t\t},", "\t\t},"]
    lines += ["\t},", "})", ""]
    folder = wow_dir / "Interface" / "AddOns" / FOLDER
    (folder / "Talents").mkdir(parents=True, exist_ok=True)
    toc = f"## Interface: 16001\n## Title: Polestar\n## X-License: GPL-3.0-only\n## Version: {TOC_VERSION}\n"
    (folder / f"{FOLDER}.toc").write_bytes(toc.encode("utf-8"))
    (folder / "Talents" / "Builds.lua").write_bytes("\n".join(lines).encode("utf-8"))
    return folder
